impl std::str::FromStr for Key {
    type Err = KeyNameError;
    fn from_str(name: &str) -> Result<Self, Self::Err> {
        Self::from_name(name).ok_or_else(|| KeyNameError(name.to_owned()))
    }
}
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct KeyNameError(pub String);
impl std::fmt::Display for KeyNameError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(formatter, "unknown physical key name '{}'", self.0)
    }
}
impl std::error::Error for KeyNameError {}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn names_round_trip_and_unknown_names_fail() {
        for key in [Key::KeyW, Key::Space, Key::ArrowUp, Key::Escape, Key::F12] {
            assert_eq!(Key::from_name(key.name()), Some(key));
            assert_eq!(key.name().parse::<Key>().unwrap(), key);
        }
        assert!(Key::from_name("NotAKey").is_none());
        assert!("NotAKey".parse::<Key>().is_err());
    }
}
